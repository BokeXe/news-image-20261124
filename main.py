#!/usr/bin/env python3
"""Entry program for news-image-20261124: copy the pre-rendered front page
to the output directory. Deterministic: no clock, no network, no randomness.
The image is generated by prep/news24/build.py and stored in this repo as
entry.png; this program only copies it byte-for-byte.
"""
import os, shutil

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    outdir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(outdir, exist_ok=True)
    dst = os.path.join(outdir, "entry.png")
    shutil.copyfile(src, dst)
    # Guard the determinism contract: the output must be the source, byte for byte.
    assert os.path.getsize(dst) == os.path.getsize(src), "copied size differs from entry.png"
    print("wrote", dst, os.path.getsize(dst), "bytes")

if __name__ == "__main__":
    main()
